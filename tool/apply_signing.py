"""Switches the release build from the debug key to your upload key (android/key.properties).
Works with both build.gradle.kts and build.gradle generated by `flutter create`."""
import os, re

kts = 'android/app/build.gradle.kts'
groovy = 'android/app/build.gradle'

if os.path.exists(kts):
    s = open(kts).read()
    head = ('import java.util.Properties\nimport java.io.FileInputStream\n\n'
            'val keystoreProperties = Properties()\n'
            'val keystorePropertiesFile = rootProject.file("key.properties")\n'
            'if (keystorePropertiesFile.exists()) { keystoreProperties.load(FileInputStream(keystorePropertiesFile)) }\n\n')
    s = head + s
    s = s.replace('    buildTypes {',
        '    signingConfigs {\n'
        '        create("release") {\n'
        '            keyAlias = keystoreProperties["keyAlias"] as String\n'
        '            keyPassword = keystoreProperties["keyPassword"] as String\n'
        '            storeFile = file(keystoreProperties["storeFile"] as String)\n'
        '            storePassword = keystoreProperties["storePassword"] as String\n'
        '        }\n'
        '    }\n\n    buildTypes {', 1)
    s = s.replace('signingConfig = signingConfigs.getByName("debug")', 'signingConfig = signingConfigs.getByName("release")')
    open(kts, 'w').write(s)
elif os.path.exists(groovy):
    s = open(groovy).read()
    head = ('def keystoreProperties = new Properties()\n'
            'def keystorePropertiesFile = rootProject.file("key.properties")\n'
            'if (keystorePropertiesFile.exists()) { keystoreProperties.load(new FileInputStream(keystorePropertiesFile)) }\n\n')
    s = re.sub(r'(\nandroid \{)', '\n' + head + r'android {', s, 1)
    s = s.replace('    buildTypes {',
        '    signingConfigs {\n        release {\n'
        '            keyAlias keystoreProperties["keyAlias"]\n'
        '            keyPassword keystoreProperties["keyPassword"]\n'
        '            storeFile file(keystoreProperties["storeFile"])\n'
        '            storePassword keystoreProperties["storePassword"]\n'
        '        }\n    }\n\n    buildTypes {', 1)
    s = s.replace('signingConfig = signingConfigs.debug', 'signingConfig = signingConfigs.release')
    s = s.replace('signingConfig signingConfigs.debug', 'signingConfig signingConfigs.release')
    open(groovy, 'w').write(s)
print('signing applied')
